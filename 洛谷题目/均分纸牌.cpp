#include <iostream>
#include <cmath>
using namespace std;

int main()
{
    int N;
    cin >> N;
    int A[105], sum = 0;
    for(int i = 1; i <= N; i++)
    {
        cin >> A[i];
        sum += A[i];
    }
    int aver = sum / N;
    int cnt = 0;
    for(int i = 1; i < N; i++)
    {
        if(A[i] != aver)
        {
            A[i+1] += A[i] - aver;
            cnt++;
        }
    }
    cout << cnt << endl;
    return 0;
}

// 思路：

// 从堆 1 开始，依次处理每一堆，将多余或不足的纸牌传递给下一堆。
// 这样可以确保每个移动都是必要的，并且总移动次数最少。
// 具体操作：

// 当 A[i] != aver 时，表示当前堆的纸牌数不符合平均值，需要进行调整。
// 计算差值：A[i] - aver。
// 如果差值为正，表示当前堆有多余的纸牌，需要移出。
// 如果差值为负，表示当前堆缺少纸牌，需要接收。
// 将差值传递给下一堆：A[i+1] += A[i] - aver;
// 这一步模拟了纸牌的移动，将当前堆与平均值的差值，传递给下一堆。
// 更新当前堆的纸牌数：不需要显式更新，因为我们关注的是差值的传递。
// 记录操作次数：

// 每当 A[i] != aver，需要进行一次调整，操作次数 cnt 加一。

// 4. 为什么这样操作有效？
// 差值累积的传递：

// 差值在传递过程中可能会累积，但最终会在后续的堆中被消化。
// 通过逐步传递差值，最终可以使所有堆的纸牌数都达到平均值。
// 符合移动规则：

// 由于只在相邻的堆之间传递差值，符合题目中纸牌只能在相邻堆之间移动的规则。
// 移动次数最少：

// 每一次调整都使得当前堆达到平均值，不会产生多余的移动。