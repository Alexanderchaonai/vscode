#include <stdio.h>
//需求：键盘录入一个三位数，将其拆分为个位，十位
//百位后，打印在控制台
//输出结果：
//个位是：3
//十位是：2
//个位是：1

int main()
//1.键盘录入一个三位数
{
    printf("请输入一个三位数:\n");
    int a;
    scanf("%d",&a);
    //2.拆分
    int ge=a%10;
    int shi=a/10%10;
    int bai=a/100%5;
 //3.打印
 printf("个位是：%d\n",ge);
 printf("十位是：%d\n",shi);
 printf("百位是：%d\n",bai);
    return 0;

    
}
//数值拆分公式总结：
//个位：数值%10
//十位：数值/10%10
//百位：数值/100%10
//千位：数值/1000%10